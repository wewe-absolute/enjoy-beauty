function getQueryVariable(variable)
{
    var query = window.location.search.substring(1);
    var vars = query.split("&");
    for (var i=0;i<vars.length;i++) {
        var pair = vars[i].split("=");
        if(pair[0] == variable){return pair[1];}
    }
    return(false);
}
$(document).ready(function () {
    let name = getQueryVariable("name");
    let info;
    for(let i=0;i<infos.length;i++){
        if(name == infos[i].name){
            info = infos[i];
        }
    }
    $("#head").css("background-image","url("+info.banner+")");
    $("#mobile_head_banner").css("background-image","url("+info.mobile_banner+")");
    $("#brandhtml-logo img").attr("src",info.logo);
    $("#brandhtml-content").html(info.content);
    if(info.hasSales){
        $("#brandhtml-sales").show();
        for(let i=0;i<info.salesImg.length;i++){
            $("#brandhtml-sales .sales-box .sales_channel").append('<img src="'+info.salesImg[i]+'"/>')
            $("#brandhtml-sales .sales-box .mobile_sales_channel .salesswiper .swiper-wrapper").append('<div class="mobile_sales_channel-item swiper-slide"><img src="'+info.salesImg[i]+'"></div>')
        }
        if(info.hasOffline){
            for(let i=0;i<info.shopsImg.length;i++){
                $("#brandhtml-sales .sales-box .shops").append('<img src="'+info.shopsImg[i]+'"/>')
            }
            if (screen.width <= 640) {
                $("#brandhtml-sales .sales-box").css("height","34.6rem");
            }
        }else{
            $("#brandhtml-sales .title").attr("src","images/sales-title2.png");
            if (screen.width <= 640) {
                $("#brandhtml-sales .title").css("margin-bottom","0.3rem");
            }
            $("#brandhtml-sales .sales-box .subtitle:first").hide();
            $("#brandhtml-sales .sales-box .shops-box").hide();
        }
        var salesswiper = new Swiper('.salesswiper', {
            on: {
                slideChange: function () {
                },
            }
        })
        $("#brandhtml-sales .sales-box .mobile_sales_channel .next").click(function () {
            salesswiper.slideNext();
        })
        $("#brandhtml-sales .sales-box .mobile_sales_channel .prev").click(function () {
            salesswiper.slidePrev();
        })
    }else{
        $("#brandhtml-sales").hide();
    }
    if(info.hasActivity){
        $("#brandhtml-activity").show();
        for(let i=0;i<info.activityImg.length;i++){
            $("#brandhtml-activity .activity-box").append('<img src="'+info.activityImg[i]+'"/>')
            $("#brandhtml-activity .mobile_activity-box").append('<img src="'+info.mobile_activityImg[i]+'"/>')
        }
    }else{
        $("#brandhtml-activity").hide();
    }
    if(info.hasPraise){
        $("#brandhtml-praise").show();
        for(let i=0;i<info.praiseImg.length;i++){
            $("#brandhtml-praise .praise-box").append('<img src="'+info.praiseImg[i]+'"/>')
        }
    }else{
        $("#brandhtml-praise").hide();
    }
}); 
